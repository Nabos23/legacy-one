async def seed_connector_registry() -> None:
    """Upsert all providers on every startup.

    Core auth config ($setOnInsert) is never overwritten so admin edits to OAuth
    URLs or scopes survive redeploys. Refreshable fields — setup_guide, is_active,
    and prompt — are always updated via $set so copy improvements reach existing
    records automatically.
    """
    await _ensure_indexes()

    inserted = 0
    updated = 0

    for provider in SEED_PROVIDERS:
        # Copy so we never mutate the module-level list.
        doc = {**provider}
        auth_type = doc.pop("auth_type")
        oauth = doc.pop("oauth", None)
        guide = doc.pop("setup_guide", None)
        is_active = doc.pop("is_active")
        prompt = doc.pop("prompt", None)
        actions = doc.pop("available_actions", None)
        doc["created_at"] = datetime.now(timezone.utc)
        # is_visible goes into $setOnInsert so admin toggles survive restarts.
        doc.setdefault("is_visible", True)

        result = await connector_registry_collection.update_one(
            {"provider_id": doc["provider_id"]},
            {
                "$setOnInsert": doc,
                "$set": {
                    "auth_type": auth_type,
                    "oauth": oauth,
                    "setup_guide": guide,
                    "is_active": is_active,
                    "prompt": prompt,
                    "available_actions": actions,
                },
            },
            upsert=True,
        )

        if result.upserted_id:
            inserted += 1
        elif result.modified_count:
            updated += 1

    logger.info("Connector registry: %d inserted, %d updated.", inserted, updated)


async def _ensure_indexes() -> None:
    """Create compound indexes so connector lookups are O(log n) not O(n)."""
    await connector_registry_collection.create_indexes([
        IndexModel([("provider_id", ASCENDING)], unique=True, name="provider_id_unique"),
        IndexModel([("is_active", ASCENDING)], name="is_active"),
    ])

    owner_unique_idx = IndexModel(
        [("connector_id", ASCENDING), ("owner_id", ASCENDING)],
        unique=True,
        name="connector_owner_unique",
    )
    # Tokens collection: non-unique lookup index only. Atlas rejects partial
    # unique indexes using $ne/$exists, so uniqueness is enforced at the
    # application layer via the upsert in exchange_code().
    # Name must match the index already created in Atlas on this key pattern.
    token_lookup_idx = IndexModel(
        [("connector_id", ASCENDING), ("owner_id", ASCENDING)],
        name="connector_owner_lookup",
    )
    state_idx = IndexModel([("state", ASCENDING)], sparse=True, name="state_sparse")

    await connector_credentials_collection.create_indexes([owner_unique_idx])
    await connector_tokens_collection.create_indexes([token_lookup_idx, state_idx])
    await connector_instances_collection.create_indexes([owner_unique_idx])